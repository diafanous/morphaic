const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const base=process.env.MORPHAIC_TEST_URL||'http://127.0.0.1:8872';
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:840,height:620}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base);await page.waitForFunction(()=>window.effectsSync&&window.studioReset);
    await page.locator('#settings').click();await page.locator('#fmt').selectOption('map');
    const originalTone=await page.locator('#m2c').inputValue();
    await page.getByRole('button',{name:'edit migration tone hue and hex',exact:true}).click();
    await page.getByLabel('tone hex code',{exact:true}).fill('#123456');
    await page.getByRole('button',{name:'done editing color'}).click();
    assert.equal(await page.locator('#m2c').inputValue(),'#123456');
    assert.equal(await page.evaluate(()=>st.map.m2c),'#123456');
    await page.locator('#undo').click();assert.equal(await page.locator('#m2c').inputValue(),originalTone);
    await page.locator('#redo').click();assert.equal(await page.locator('#m2c').inputValue(),'#123456');
    await page.getByRole('button',{name:'edit migration tone hue and hex',exact:true}).click();
    await page.getByLabel('tone hex code',{exact:true}).fill('invalid');
    assert.equal(await page.locator('#m2c').inputValue(),'#123456');
    await page.getByLabel('tone hex code',{exact:true}).fill('#ff0000');
    await page.getByLabel('tone hue',{exact:true}).fill('120');
    await page.getByRole('button',{name:'done editing color'}).click();
    assert.equal(await page.locator('#m2c').inputValue(),'#00ff00');
    await page.locator('#lineByShape').check();await page.locator('#lineToneGradient').check();await page.locator('#lineOpacityGradient').check();
    assert(await page.locator('#line-triangle').isVisible());
    assert(await page.locator('#m2_gradient_end').isDisabled());
    await page.locator('#m2so_pct').fill('25');await page.locator('#m2so_pct').press('Tab');
    await page.locator('#m2eo_pct').fill('75');await page.locator('#m2eo_pct').press('Tab');
    assert.deepEqual(await page.evaluate(()=>[st.map.m2so,st.map.m2eo]),[.25,.75]);
    assert(await page.evaluate(()=>[...document.querySelectorAll('input[type=color]')].filter(el=>!el.closest('#toneEditor')).every(el=>el.parentElement.querySelector('.tone-edit'))));
    assert(await page.evaluate(()=>[...document.querySelectorAll('input[type=range][aria-label*="opacity"]')].every(el=>el.getAttribute('aria-valuetext')?.endsWith('%'))));
    await page.locator('#m2w').fill('2.5');await page.locator('#m2w').press('Tab');
    await page.locator('#closeSettings').click();
    await page.locator('#gradientDisclosure summary').click();await page.locator('#gradientAdd').click();
    await page.waitForFunction(()=>document.querySelectorAll('#gradientStops .tone-edit').length===3);
    const png=Buffer.from(await page.evaluate(()=>{const c=document.createElement('canvas');c.width=96;c.height=64;return c.toDataURL().split(',')[1];}),'base64');
    await page.locator('#pick').setInputFiles({name:'map.png',mimeType:'image/png',buffer:png});
    await page.waitForFunction(()=>st.files.length===1);
    await page.locator('#settings').click();
    await page.locator('#map_file').selectOption('png');await page.locator('#dpi').fill('100');await page.locator('#dpi').press('Tab');
    await page.evaluate(()=>document.querySelector('#lines').checked=true);
    const saved=page.waitForResponse(r=>r.url().endsWith('/export/map'));
    await page.locator('#go').click();const response=await saved;assert.equal(response.status(),200);
    assert((await response.json()).name.endsWith('.png'));
    await page.locator('#fmt').selectOption('triptych');
    assert(await page.locator('#triptychMenu').isVisible());
    await page.locator('#triptych_file').selectOption('pdf');
    const pdf=page.waitForResponse(r=>r.url().endsWith('/export/triptych'));
    await page.locator('#go').click();const triptych=await pdf;
    assert.equal(triptych.status(),200);assert((await triptych.json()).name.endsWith('.pdf'));
    await page.locator('#fmt').selectOption('map');
    assert(!(await page.locator('#triptychMenu').isVisible()));
    await page.locator('#saveMapDefaults').click();
    await page.reload();await page.waitForFunction(()=>window.effectsSync&&window.studioReset&&st.map.line_by_shape);
    assert.deepEqual(await page.evaluate(()=>[st.map.m2w,st.map.m2so,st.map.m2eo,st.map.line_tone_gradient]),[2.5,.25,.75,true]);
    assert.deepEqual(errors,[]);
    console.log('ok: map single-file PNG, cut-shape colors, line gradients, independent node percentages, all tone tools, hue/hex and saved defaults');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
